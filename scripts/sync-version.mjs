// Writes src/version.ts from package.json so the runtime version can't drift.
import { readFileSync, writeFileSync } from 'node:fs'

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const out = `// Generated by scripts/sync-version.mjs from package.json. Do not edit.
export const BEAM_VERSION = '${pkg.version}'
`
const target = new URL('../src/version.ts', import.meta.url)
let current = ''
try { current = readFileSync(target, 'utf8') } catch {}
if (current !== out) writeFileSync(target, out)
